/** Countries offered to a new app before it has any of its own */
export const PRESET_COUNTRIES = ["us", "gb", "ca", "au", "de"] as const;

export type Country = { code: string; name: string; flag: string };

/** Flag emoji from a two-letter code, via regional indicator symbols. */
export function countryFlag(code: string): string {
  const upper = code.toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) return "";
  return String.fromCodePoint(
    ...[...upper].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65),
  );
}

export function countryName(code: string): string {
  return COUNTRY_NAMES[code.toLowerCase()] ?? code.toUpperCase();
}

export function getCountry(code: string): Country {
  const lower = code.toLowerCase();
  return { code: lower, name: countryName(lower), flag: countryFlag(lower) };
}

/** Every storefront, sorted by name. */
export const COUNTRIES: Country[] = Object.keys(COUNTRY_NAMES)
  .map(getCountry)
  .sort((a, b) => a.name.localeCompare(b.name, "en"));
